uint8_t FontIndex(char c)
{
    if (c >= 'a' && c <= 'z') c -= 'a' - 'A';
    if (c >= 'A' && c <= 'Z') return c - 'A';
    if (c >= '0' && c <= '9') return 26 + c - '0';
    switch (c)
    {
        case '/': return 37;
        case '-': return 38;
        case '.': return 39;
        case ':': return 40;
        default: return 36;
    }
}

uint8_t FontRow(uint8_t index, uint8_t row)
{
    if (index >= sizeof(font) / sizeof(font[0]) || row >= 7) return 0;
    return pgm_read_byte(&font[index][row]);
}
